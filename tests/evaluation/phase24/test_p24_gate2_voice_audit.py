"""
tests/evaluation/phase24/test_p24_gate2_voice_audit.py

Automated test suite verifying the Phase 24 Gate 2 Voice Stack Control Surface Audit dataset.
Ensures that all 30 benchmark runs (15 English + 15 Northern Vietnamese) meet acoustic integrity,
pitch-tracking preservation, duration preservation, headroom safety, and latency instrumentation standards.
"""

import json
from pathlib import Path
import pytest

BENCHMARK_DIR = Path(__file__).resolve().parent / "voice_benchmark"
RAW_TELEMETRY_PATH = BENCHMARK_DIR / "raw_benchmark_telemetry.json"
CSV_PATH = BENCHMARK_DIR / "acoustic_summary.csv"


@pytest.fixture(scope="module")
def telemetry():
    assert RAW_TELEMETRY_PATH.exists(), f"Raw telemetry missing at {RAW_TELEMETRY_PATH}"
    with open(RAW_TELEMETRY_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def test_telemetry_completeness(telemetry):
    """Verify exact 30 utterances (15 EN + 15 VI) with complete metadata."""
    results = telemetry["results"]
    assert len(results) == 30, f"Expected 30 utterances, got {len(results)}"
    en_cases = [r for r in results if r["lang"] == "en"]
    vi_cases = [r for r in results if r["lang"] == "vi"]
    assert len(en_cases) == 15, f"Expected 15 English cases, got {len(en_cases)}"
    assert len(vi_cases) == 15, f"Expected 15 Vietnamese cases, got {len(vi_cases)}"


def test_all_rvc_conversions_succeeded(telemetry):
    """Verify 100% conversion success with real neural vocoder outputs."""
    for r in telemetry["results"]:
        post = r["post_rvc"]
        assert post["duration_s"] > 1.0, f"{r['id']} produced zero or truncated audio"
        assert post["voiced_fraction"] > 0.30, f"{r['id']} has unusually low voiced fraction: {post['voiced_fraction']}"
        assert post["f0_mean"] > 100.0, f"{r['id']} has invalid mean F0: {post['f0_mean']}"


def test_duration_preservation_accuracy(telemetry):
    """Verify that RVC preserves Edge-TTS duration within +/- 1% across all 30 utterances."""
    for r in telemetry["results"]:
        ratio = r["derived"]["duration_preservation_ratio"]
        assert 0.990 <= ratio <= 1.005, (
            f"{r['id']} duration preservation ratio out of bounds: {ratio:.4f}"
        )


def test_headroom_guard_and_zero_clipping(telemetry):
    """Verify headroom normalization prevents digital clipping (peak <= 0.95, clipping == 0)."""
    for r in telemetry["results"]:
        post = r["post_rvc"]
        assert post["peak"] <= 0.95, f"{r['id']} exceeded headroom guard: peak={post['peak']}"
        assert post["clipping_ratio"] == 0.0, f"{r['id']} exhibited hard clipping: {post['clipping_ratio']}"


def test_f0_pitch_preservation_fidelity(telemetry):
    """Verify that RVC faithfully tracks the pitch shifts generated by Edge-TTS."""
    for r in telemetry["results"]:
        disc = abs(r["derived"]["rvc_f0_discrepancy_hz"])
        # All conditions must preserve F0 within 10 Hz of Edge-TTS input
        assert disc < 10.0, f"{r['id']} F0 tracking discrepancy exceeded 10 Hz: {disc:.2f} Hz"


def test_csv_artifact_validity():
    """Verify acoustic_summary.csv is well-formed with 31 lines (1 header + 30 rows)."""
    assert CSV_PATH.exists(), f"CSV summary missing at {CSV_PATH}"
    with open(CSV_PATH, "r", encoding="utf-8") as f:
        lines = [line.strip() for line in f if line.strip()]
    assert len(lines) == 31, f"Expected 31 lines (1 header + 30 data), got {len(lines)}"
