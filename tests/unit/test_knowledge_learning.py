        assert derived_prop.subject == "4+2"
        assert derived_prop.object == "6"
        assert derived_prop.provenance == ProvenanceType.DERIVED

        # Verify queryable from store
        query_res = arithmetic_store.query(subject="4+2", predicate="equals")
        assert len(query_res) == 1
        assert query_res[0].object == "6"


