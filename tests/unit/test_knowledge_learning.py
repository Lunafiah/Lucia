        p_2plus2 = restored_store.query(subject="2+2")
        assert len(p_2plus2) == 1
        assert p_2plus2[0].object == "4"
        assert p_2plus2[0].provenance == ProvenanceType.USER_STATED

        p_4plus2 = restored_store.query(subject="4+2")
        assert len(p_4plus2) == 1
        assert p_4plus2[0].object == "6"
        assert p_4plus2[0].provenance == ProvenanceType.DERIVED
