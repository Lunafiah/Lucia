class TestK_EXP_12_Persistence:
    """K-EXP-12: Verify complete export and reconstruction across process restart."""

    def test_json_serialization_round_trip(self, arithmetic_store: KnowledgeStore) -> None:
        # Add a derived proposition and revision
        engine = DerivationEngine()
        engine.derive_peano_addition(arithmetic_store, 4, 2)

        # Export to JSON
        json_str = arithmetic_store.to_json()
