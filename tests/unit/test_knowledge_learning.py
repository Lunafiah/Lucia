# K-EXP-11: Four-Condition Ablation
# ==============================================================================


class TestK_EXP_11_Ablation:
    """
    K-EXP-11: Comparative benchmark of four distinct operational conditions:
      - Condition A: LLM Available, Knowledge Store Unavailable
      - Condition B: LLM Unavailable, Knowledge Store Available (Lookup only)
      - Condition C: LLM Unavailable, Knowledge Store Available + Derivation Active
      - Condition D: LLM Available + Knowledge Store Available
    """

    def _execute_harness(
        self,
        query_prompt: str,
        llm_available: bool,
        store_available: bool,
        derivation_active: bool,
        store: Optional[KnowledgeStore],
    ) -> Dict[str, Any]:
        """Simulation harness testing epistemic source attribution."""
        result = {
            "answer": None,
            "source": None,
            "provenance": None,
            "derived": False,
        }

        # Step 1: Query internal store if available
        if store_available and store is not None:
            matches = store.query(subject=query_prompt, valid_only=True)
            if matches:
                result["answer"] = matches[0].object
                result["source"] = "LUCIA_KNOWLEDGE_STORE"
                result["provenance"] = matches[0].provenance.value
                return result

            # Step 2: If no direct match, attempt derivation if active
            if derivation_active:
                # E.g. query "4+2" -> split and derive
                if "+" in query_prompt:
                    parts = query_prompt.split("+")
                    try:
                        a, b = int(parts[0]), int(parts[1])
                        engine = DerivationEngine()
                        derived_prop = engine.derive_peano_addition(store, a, b)
                        result["answer"] = derived_prop.object
                        result["source"] = "LUCIA_DERIVATION_ENGINE"
                        result["provenance"] = derived_prop.provenance.value
                        result["derived"] = True
                        return result
                    except ValueError:
                        pass

        # Step 3: Fallback to LLM if available
        if llm_available:
            # Simulated LLM parametric recall
            result["answer"] = "6"
            result["source"] = "LLM_PARAMETRIC_MEMORY"
            result["provenance"] = "LLM_GENERATED"
            return result

        result["answer"] = None
        result["source"] = "UNKNOWN"
        result["provenance"] = "UNANSWERED"
        return result

    def test_condition_a_llm_only(self) -> None:
        """Condition A: LLM available, store unavailable. Source is LLM parametric."""
        res = self._execute_harness("4+2", llm_available=True, store_available=False,
                                    derivation_active=False, store=None)
        assert res["answer"] == "6"
        assert res["source"] == "LLM_PARAMETRIC_MEMORY"
        assert res["provenance"] == "LLM_GENERATED"

    def test_condition_b_store_only_without_derivation(
        self, arithmetic_store: KnowledgeStore
    ) -> None:
        """Condition B: Store available (only contains 2+2 and 3+2), LLM disabled, derivation off."""
        res = self._execute_harness("4+2", llm_available=False, store_available=True,
                                    derivation_active=False, store=arithmetic_store)
        # Cannot answer because 4+2 was not memorized and derivation is off
        assert res["answer"] is None
        assert res["source"] == "UNKNOWN"

    def test_condition_c_store_with_derivation(
        self, arithmetic_store: KnowledgeStore
    ) -> None:
        """Condition C: Store available + Derivation active, LLM disabled."""
        res = self._execute_harness("4+2", llm_available=False, store_available=True,
                                    derivation_active=True, store=arithmetic_store)
        # Successfully answers via symbolic derivation from stored rules
        assert res["answer"] == "6"
        assert res["source"] == "LUCIA_DERIVATION_ENGINE"
        assert res["provenance"] == ProvenanceType.DERIVED.value
        assert res["derived"] is True

    def test_condition_d_store_and_llm(
        self, arithmetic_store: KnowledgeStore
    ) -> None:
        """Condition D: Store and LLM available. Store derivation takes precedence."""
        res = self._execute_harness("4+2", llm_available=True, store_available=True,
                                    derivation_active=True, store=arithmetic_store)
        assert res["answer"] == "6"
        assert res["source"] == "LUCIA_DERIVATION_ENGINE"


