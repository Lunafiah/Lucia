class TestK_EXP_10_Revision:
    """K-EXP-10: Update beliefs with verified evidence while preserving historical provenance."""

    def test_belief_revision_preserves_history(self, empty_store: KnowledgeStore) -> None:
        # Old belief (pre-measurement)
        p_old = Proposition(
            id="p:pluto_planet", subject="Pluto", predicate="classified_as", object="planet",
            confidence=0.80, provenance=ProvenanceType.USER_STATED,
        )
        empty_store.store_proposition(p_old)

        # New verified belief (IAU 2006 reclassification)
        p_new = Proposition(
            id="p:pluto_dwarf", subject="Pluto", predicate="classified_as", object="dwarf_planet",
            confidence=0.99, provenance=ProvenanceType.VERIFIED,
        )

        empty_store.revise(p_old.id, p_new, reason="IAU Resolution B5 2006")

        # Invariant 1: Old proposition is invalidated, not deleted
        old_retrieved = empty_store.get_proposition(p_old.id)
        assert old_retrieved is not None
        assert old_retrieved.valid is False
        assert old_retrieved.provenance == ProvenanceType.CONTRADICTED
        assert old_retrieved.superseded_by == p_new.id

        # Invariant 2: Active query returns ONLY the new belief
        active_query = empty_store.query(subject="Pluto", valid_only=True)
        assert len(active_query) == 1
        assert active_query[0].object == "dwarf_planet"

        # Invariant 3: Audit log preserves revision trace
        assert len(empty_store._revision_history) == 1
        record = empty_store._revision_history[0]
        assert record["old_id"] == p_old.id
        assert record["new_id"] == p_new.id
        assert record["reason"] == "IAU Resolution B5 2006"


